export function getSampleCoinHistory(code, currency = "USD", range = "24h") {
  const coins = getSampleCoins(currency);
  const coin = coins.find((c) => c.code.toUpperCase() === String(code).toUpperCase());
  if (!coin) return null;

  const now = Date.now();
  const rangeMap = {
    "24h": { ms: 24 * 60 * 60 * 1000, pct: coin.changes.h24, pts: 72 },
    "7d": { ms: 7 * 24 * 60 * 60 * 1000, pct: coin.changes.d7, pts: 84 },
    "1m": { ms: 30 * 24 * 60 * 60 * 1000, pct: coin.changes.d30, pts: 90 },
    "3m": { ms: 90 * 24 * 60 * 60 * 1000, pct: coin.changes.d90, pts: 90 },
    "1y": { ms: 365 * 24 * 60 * 60 * 1000, pct: coin.changes.y1, pts: 100 },
    max: { ms: 3 * 365 * 24 * 60 * 60 * 1000, pct: coin.changes.y1 * 1.8, pts: 110 },
  };
  const cfg = rangeMap[range] ?? rangeMap["24h"];
  const isStable = coin.categories.includes("Stablecoins") && coin.rate < 5;

  return generateSeries({
    endPrice: coin.rate,
    pctChange: cfg.pct,
    pointsCount: cfg.pts,
    seedKey: `${coin.code}:${range}`,
    startTimeMs: now - cfg.ms,
    endTimeMs: now,
    baseVolume: coin.volume,
    baseCap: coin.cap,
    stable: isStable,
  });
}

