export function getSampleExchanges(currency = "USD") {
  const fx = getFxMultiplier(currency);
  return BASE_EXCHANGES.map((ex, idx) => {
    const volume = ex.volume * fx;
    const bidTotal = ex.bidTotal * fx;
    const askTotal = ex.askTotal * fx;
    const depth = bidTotal + askTotal;
    return {
      rank: idx + 1,
      code: ex.code,
      name: ex.name,
      color: ex.color,
      icon: null,
      centralized: ex.centralized,
      usCompliant: ex.usCompliant,
      markets: ex.markets,
      volume,
      bidTotal,
      askTotal,
      depth,
      visitors: ex.visitors,
      volumePerVisitor: ex.visitors > 0 ? volume / ex.visitors : 0,
      website: ex.website,
    };
  });
}
