function hashSeed(str) {
  let h = 2166136261;
  for (let i = 0; i < str.length; i += 1) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

function mulberry32(seed) {
  let t = seed >>> 0;
  return () => {
    t += 0x6d2b79f5;
    let r = Math.imul(t ^ (t >>> 15), 1 | t);
    r ^= r + Math.imul(r ^ (r >>> 7), 61 | r);
    return ((r ^ (r >>> 14)) >>> 0) / 4294967296;
  };
}

export function generateSeries({
  endPrice,
  pctChange,
  pointsCount = 48,
  seedKey = "BTC",
  startTimeMs,
  endTimeMs,
  baseVolume = 1_000_000_000,
  baseCap = 10_000_000_000,
  stable = false,
}) {
  const rand = mulberry32(hashSeed(seedKey));
  const clampedPct = Number.isFinite(pctChange) ? pctChange : 0;
  const startPrice = endPrice / (1 + clampedPct / 100 || 1);
  const volatility = stable
    ? 0.0006
    : Math.max(0.012, Math.min(0.08, Math.abs(clampedPct) / 140 + 0.016));

  const raw = [0];
  for (let i = 1; i < pointsCount; i += 1) {
    const step = (rand() - 0.5) * 2 * volatility;
    raw.push(raw[i - 1] + step);
  }
  const endOffset = raw[raw.length - 1];

  const series = [];
  const span = Math.max(1, endTimeMs - startTimeMs);
  for (let i = 0; i < pointsCount; i += 1) {
    const progress = i / (pointsCount - 1);
    const bridge = raw[i] - progress * endOffset;
    const trendPrice = startPrice + (endPrice - startPrice) * progress;
    const rate = Math.max(
      endPrice * 0.1,
      i === pointsCount - 1 ? endPrice : trendPrice * (1 + bridge),
    );
    const ratio = endPrice > 0 ? rate / endPrice : 1;
    series.push({
      date: Math.round(startTimeMs + span * progress),
      rate,
      volume: Math.round(baseVolume * (0.65 + rand() * 0.7)),
      cap: Math.round(baseCap * ratio),
    });
  }
  return series;
}

export function getFxMultiplier(currency) {
  const upper = String(currency || "USD").toUpperCase();
  return SAMPLE_FX[upper] ?? 1;
}

